"""Chatbot agent: a ReAct-style tool-calling assistant on top of CampusInbox.

The student asks questions in plain language; the chatbot runs an explicit
ReAct loop [Yao et al., 2022]: it THINKS which tool would help, ACTS by
calling the tool, reads the OBSERVATION, and repeats until it can answer.

Honesty note: in demo mode (no LLM API key) the "Thought" steps come from a
deterministic rule-based planner, not a language model - the reasoning text is
generated by code so the loop can be studied and tested offline. The tools,
the vector-store retrieval and the web calls are real. Wiring an actual model
(e.g. Gemini) to produce the thoughts is the LangGraph/API-key extension.
"""
from __future__ import annotations

import re
from datetime import date

from .tools.core import parse_date
from .tools.vectorstore import VectorStore
from .tools.websearch import web_search

MAX_REACT_STEPS = 4


class ChatbotAgent:
    name = "chatbot"

    def __init__(self, state=None, live_web: bool = True):
        self.state = state
        self.live_web = live_web
        self.store = VectorStore()
        if state:
            for mail in state.mails:
                self.store.add_mail(mail.subject, mail.body)
        self.tools = {
            "list_deadlines": self._t_list_deadlines,
            "deadlines_for_course": self._t_course,
            "next_deadline": self._t_next,
            "parse_a_date": self._t_parse_date,
            "search_mails": self._t_search_mails,
            "web_search": self._t_web,
        }

    # ----- tool implementations -----
    def _t_list_deadlines(self, **_):
        planned = self.state.planned if self.state else []
        if not planned:
            return "No deadlines loaded yet. Run the pipeline first."
        lines = [f"- {i['deadline'].course}: {i['deadline'].what} (due {i['deadline'].due})"
                 for i in planned]
        return "All proposed deadlines:\n" + "\n".join(lines)

    def _t_course(self, course="", **_):
        planned = self.state.planned if self.state else []
        hits = [i for i in planned if i["deadline"].course.lower() == course.lower()]
        if not hits:
            return f"No deadlines tagged {course}."
        return "\n".join(f"- {i['deadline'].what} (due {i['deadline'].due})" for i in hits)

    def _t_next(self, **_):
        planned = self.state.planned if self.state else []
        upcoming = [i["deadline"] for i in planned if i["deadline"].due >= date.today()]
        if not upcoming:
            return "Nothing upcoming."
        nxt = min(upcoming, key=lambda d: d.due)
        return f"Next up: {nxt.what} ({nxt.course}) on {nxt.due} - in {(nxt.due - date.today()).days} day(s)."

    def _t_parse_date(self, text="", **_):
        due = parse_date(text, date.today())
        return f"'{text}' parses to {due}." if due else f"Could not parse a date from '{text}'."

    def _t_search_mails(self, query="", **_):
        hits = self.store.search(query, k=3)
        if not hits:
            return f"No mail sentence matches '{query}'."
        return "\n".join(
            f"- (score {h['score']}, from '{h['source']}') \"{h['text']}\"" for h in hits)

    def _t_web(self, query="", **_):
        res = web_search(query, live=self.live_web)
        head = f"[web_search mode: {res['mode']}]"
        body = "\n".join(f"- {r['title']} {r['url']}\n  {r['snippet']}" for r in res["results"])
        return head + "\n" + body

    # ----- ReAct loop: plan tools, then think/act/observe one step at a time -----
    def plan_tools(self, question: str) -> list[tuple[str, dict]]:
        """Demo-mode planner (rule-based): decide which tools a question needs."""
        q = question.lower()
        calls = []
        if re.search(r"\b(search|web|google|look up|online|internet)\b", q):
            query = re.sub(r"\b(search|web|google|look up|for|online|internet|the)\b", "", q)
            query = re.sub(r"\s+", " ", query).strip(" ?.")
            calls.append(("web_search", {"query": query}))
        if re.search(r"\bnext|upcoming|soonest\b", q):
            calls.append(("next_deadline", {}))
        for course in ("agentic", "oomd", "placement", "ds"):
            if course in q and "deadline" in q or f"{course} deadlines" in q:
                name = {"agentic": "Agentic AI", "ds": "DS"}.get(course, course.upper() if course == "oomd" else course.title())
                calls.append(("deadlines_for_course", {"course": name}))
        if re.search(r"\ball\b.*\bdeadline|list|show.*deadline|what.*due\b", q):
            calls.append(("list_deadlines", {}))
        m = re.search(r"parse ['\"](.+)['\"]", q)
        if m:
            calls.append(("parse_a_date", {"text": m.group(1)}))
        if not calls:
            # open question -> retrieve from the mails themselves (vector store)
            calls.append(("search_mails", {"query": question.strip(" ?.")}))
        return calls

    # backwards-compatible name used by earlier tests
    pick_tools = plan_tools

    _WHY = {
        "list_deadlines": "I should list every proposed deadline",
        "deadlines_for_course": "I should filter deadlines to that course",
        "next_deadline": "I should find the soonest upcoming deadline",
        "parse_a_date": "I should parse that date expression",
        "search_mails": "I should search the mail vectors for matching sentences",
        "web_search": "I should look this up on the web",
    }

    def react(self, question: str) -> dict:
        """Run the explicit ReAct loop. Returns {trace, answer, steps}."""
        plan = self.plan_tools(question)[:MAX_REACT_STEPS]
        trace = []
        observations = []
        for tool_name, kwargs in plan:
            thought = f"Thought: {self._WHY[tool_name]}."
            action = f"Action: {tool_name}({kwargs})"
            observation = self.tools[tool_name](**kwargs)
            trace.extend([thought, action, f"Observation: {observation}"])
            observations.append(observation)
        trace.append("Thought: I now have what I need to answer.")
        answer = observations[-1] if observations else "I could not find an answer."
        trace.append(f"Final answer: {answer}")
        return {"trace": "\n".join(trace), "answer": answer, "steps": len(plan)}

    def ask(self, question: str) -> str:
        return self.react(question)["trace"]
